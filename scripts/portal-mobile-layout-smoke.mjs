import { chromium } from "playwright";
import fs from "node:fs/promises";

await fs.mkdir(".tmp/browser", { recursive:true });
const browser=await chromium.launch({headless:true,executablePath:"/Applications/Google Chrome.app/Contents/MacOS/Google Chrome"});
const page=await browser.newPage({viewport:{width:390,height:844},isMobile:true,deviceScaleFactor:2});
const errors=[];
page.on("pageerror",error=>errors.push(error.message));
const target=process.env.PORTAL_URL||"http://127.0.0.1:4173/?event=meeting-diamjsep26-729882-41018#lookup";
const tab=process.env.PORTAL_TAB||"lookup";
const screenshot=`.tmp/browser/${process.env.PORTAL_URL?"production-":""}mobile-portal-${tab}-compact.png`;
await page.goto(target,{waitUntil:"domcontentloaded"});
await page.waitForSelector("#publicProjectFacts:not(.is-hidden)");
await page.locator(`[data-portal-tab="${tab}"]`).click();
await page.waitForFunction(()=>document.querySelectorAll("#publicProjectFacts > div").length===4);
const facts=await page.locator("#publicProjectFacts > div").evaluateAll(nodes=>nodes.map(node=>{const r=node.getBoundingClientRect();return{x:Math.round(r.x),y:Math.round(r.y),width:Math.round(r.width),height:Math.round(r.height)}}));
const tabs=await page.locator(".portal-tabs .portal-tab").evaluateAll(nodes=>nodes.map(node=>{const r=node.getBoundingClientRect();return{x:Math.round(r.x),y:Math.round(r.y),width:Math.round(r.width),height:Math.round(r.height)}}));
const title=await page.locator("#publicPortalTitle").evaluate(node=>{const r=node.getBoundingClientRect();return{fontSize:parseFloat(getComputedStyle(node).fontSize),y:Math.round(r.y),height:Math.round(r.height)}});
const card=await page.locator(".portal-card").boundingBox();
const purpose=page.locator(`[data-portal-panel="${tab}"] .portal-purpose-note`);
if(facts.length!==4||Math.abs(facts[0].y-facts[1].y)>2||Math.abs(facts[2].y-facts[3].y)>2||facts[2].y<=facts[0].y)throw new Error("Project facts are not arranged two per row");
if(tabs.length!==3||Math.max(...tabs.map(item=>item.y))-Math.min(...tabs.map(item=>item.y))>2)throw new Error("Portal actions are not arranged in one row");
if(title.fontSize>24)throw new Error(`Mobile platform title is still too large: ${title.fontSize}px`);
if(!card||card.y>320)throw new Error(`Portal actions start too low: ${card?.y}px`);
if(!await purpose.isVisible()||!(await purpose.textContent())?.includes("用途"))throw new Error(`Purpose reminder is not visible for ${tab}`);
const overflow=await page.evaluate(()=>document.documentElement.scrollWidth-document.documentElement.clientWidth);
if(overflow>1)throw new Error(`Mobile horizontal overflow: ${overflow}px`);
await page.screenshot({path:screenshot,fullPage:true});
console.log(JSON.stringify({layout:"pass",target,tab,viewport:"390x844",facts,tabs,title,portalCardY:Math.round(card.y),overflow,errors},null,2));
await browser.close();
if(errors.length)process.exitCode=1;
