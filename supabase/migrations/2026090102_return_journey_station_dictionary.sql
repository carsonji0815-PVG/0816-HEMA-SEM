create table if not exists public.station_dict(
  id bigint generated by default as identity primary key,
  city_name text not null,
  transport_type text not null check(transport_type in ('PLANE','HIGH_SPEED_RAIL')),
  station_name text not null,
  station_short_name text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique(city_name,transport_type,station_name)
);
create index if not exists station_dict_city_transport_idx on public.station_dict(city_name,transport_type);
alter table public.station_dict enable row level security;
drop policy if exists station_dict_read on public.station_dict;
create policy station_dict_read on public.station_dict for select to authenticated using (true);
drop policy if exists station_dict_admin_write on public.station_dict;
create policy station_dict_admin_write on public.station_dict for all to authenticated using (public.is_system_admin()) with check (public.is_system_admin());

