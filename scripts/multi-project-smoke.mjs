import { chromium } from "playwright";

const browser = await chromium.launch({headless:true,executablePath:"/Applications/Google Chrome.app/Contents/MacOS/Google Chrome"});
const page = await browser.newPage({viewport:{width:1280,height:900}});
const errors=[]; page.on("pageerror",error=>errors.push(error.message));
await page.addInitScript(()=>Object.defineProperty(window,"APP_CONFIG",{value:{mode:"demo"},writable:false,configurable:false}));
await page.goto("http://127.0.0.1:4173/#projects",{waitUntil:"domcontentloaded"});
await page.locator("#loginDialog").evaluate(dialog=>{if(dialog.open)dialog.close();});
await page.waitForSelector('[data-page="projects"].active');
if (await page.locator("#projectSelect option").count()<1) throw new Error("Project selector is empty");
const actionLayout=await page.locator(".project-primary-actions .button").first().evaluate(node=>{const rect=node.getBoundingClientRect(),style=getComputedStyle(node);return{width:rect.width,height:rect.height,writingMode:style.writingMode}});
if(actionLayout.width<76||actionLayout.height>54||actionLayout.writingMode!=="horizontal-tb")throw new Error(`Project actions are cramped or vertical: ${JSON.stringify(actionLayout)}`);
const compactLayout=await page.locator(".project-card").first().evaluate(node=>{
  const rect=node.getBoundingClientRect();
  const heading=document.querySelector('[data-page="projects"] .page-heading h1');
  return{height:rect.height,headingSize:Number.parseFloat(getComputedStyle(heading).fontSize)};
});
if(compactLayout.height>470||compactLayout.headingSize>36)throw new Error(`Meeting center is not compact: ${JSON.stringify(compactLayout)}`);
await page.click("#newProjectButton");
await page.selectOption('#projectForm [name="activityType"]',"internal");
await page.fill('#projectForm [name="identifier"]',"HT-NEW-2026");
await page.fill('#projectForm [name="name"]',"新会议项目");
await page.fill('#projectForm [name="activityOwner"]',"林悦");
await page.fill('#projectForm [name="activityDate"]',"2026-08-21");
await page.click('#projectForm button[type="submit"]');
await page.waitForFunction(() => [...document.querySelectorAll("#projectSelect option")].some(option => option.textContent.includes("新会议项目")));
if (!await page.locator("#projectGrid").innerText().then(text=>text.includes("新会议项目"))) throw new Error("New project card missing");
const qrLink=await page.locator(".qr-direct-link").getAttribute("href");
if (!qrLink?.includes("event=meeting-ht-new-2026")) throw new Error("Public project link has no auto-generated event slug");
const activeSlug=new URL(qrLink).searchParams.get("event");
if (!activeSlug?.startsWith("meeting-ht-new-2026")) throw new Error("Created project slug is invalid");
if (new URL(page.url()).searchParams.get("event")!==activeSlug) throw new Error(`Active project was not written to the management URL: ${page.url()}`);
const activePublicLinks=await page.locator("[data-current-public-link]").evaluateAll(links=>links.map(link=>link.href));
if (!activePublicLinks.length||activePublicLinks.some(link=>new URL(link).searchParams.get("event")!==activeSlug||!link.endsWith("#portal"))) throw new Error("Current-project portal links are inconsistent");
const projectPortalLinks=await page.locator('#projectGrid a', {hasText:"打开报名界面"}).evaluateAll(links=>links.map(link=>link.href));
if (projectPortalLinks.length<2||!projectPortalLinks.some(link=>link.includes("event=hema-sem-2026"))||!projectPortalLinks.some(link=>new URL(link).searchParams.get("event")===activeSlug)) throw new Error("Project cards do not link to their own registration portals");
await page.selectOption("#projectSelect","demo-hema");
await page.waitForFunction(()=>new URL(location.href).searchParams.get("event")==="hema-sem-2026");
const switchedLink=await page.locator(".qr-direct-link").getAttribute("href");
if (!switchedLink?.includes("event=hema-sem-2026")) throw new Error("Portal link did not follow the selected project");
console.log(JSON.stringify({projectSelector:"pass",projectCardLayout:"pass",projectCompactLayout:"pass",createProject:"pass",projectPublicUrl:"pass",projectQuerySync:"pass",projectCardPortals:"pass",errors},null,2));
await browser.close(); if(errors.length)process.exitCode=1;
