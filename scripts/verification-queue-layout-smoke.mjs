import {chromium} from "playwright";

const base="http://127.0.0.1:4173/";
const browser=await chromium.launch({headless:true,executablePath:"/Applications/Google Chrome.app/Contents/MacOS/Google Chrome"});
const page=await browser.newPage({viewport:{width:1440,height:1000}});
const errors=[];page.on("pageerror",error=>errors.push(error.message));
await page.route(base,async route=>{const response=await route.fetch();const html=(await response.text()).replace('mode: "production"','mode: "demo"');await route.fulfill({response,body:html,headers:{...response.headers(),"content-type":"text/html; charset=utf-8"}});});
await page.goto(`${base}#verification`,{waitUntil:"domcontentloaded"});
await page.evaluate(()=>localStorage.setItem("lilly-meeting-system-preferences-v1",JSON.stringify({variflightGlobalEnabled:true,variflightDailyLimit:5,variflightUnlimited:false})));
await page.reload({waitUntil:"domcontentloaded"});
await page.waitForSelector(".verify-compact-table");
const rows=page.locator(".verify-compact-row");
if(await rows.count()<4)throw new Error("Compact verification table did not render enough roster journeys");
const detail=page.locator(".verify-detail-row").first();
if(!await detail.isHidden())throw new Error("Journey details must be collapsed by default");
await rows.first().locator("[data-toggle-verification-detail]").click();
if(!await detail.isVisible())throw new Error("Journey details did not expand");
const flightToggle=page.locator("[data-disable-flight-query]").first();
if(await flightToggle.isDisabled()||!await flightToggle.isChecked())throw new Error("Global flight switch did not enable per-row query by default");
await flightToggle.uncheck();
if(!await flightToggle.locator("xpath=ancestor::tr").evaluate(row=>row.classList.contains("verify-flight-disabled")))throw new Error("Per-row flight query disable was not retained visually");
const selections=page.locator("[data-select-verification]:not(:disabled)");
await selections.nth(0).check();await selections.nth(1).check();
if(!await page.locator("#verifyRosterButton").innerText().then(text=>text.includes("(2)")))throw new Error("Batch selection count is incorrect");
if(!await page.locator("#verificationGlobalFlightEnabled").isDisabled())throw new Error("Non-super-admin must not modify the global flight switch");
await page.screenshot({path:".tmp/browser/verification-queue-layout.png",fullPage:true});
const compactRows=await rows.count();
await browser.close();
if(errors.length)throw new Error(errors.join(" | "));
console.log(JSON.stringify({compactRows,details:"pass",perRowFlightDisable:"pass",batchSelection:"pass",adminOnlyGlobalSwitch:"pass"},null,2));
