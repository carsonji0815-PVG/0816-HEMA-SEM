  return_depart_transport_type=coalesce(return_depart_transport_type,case when coalesce(return_no,'') ilike '%本地参会%' then 'LOCAL_ATTEND' when coalesce(return_no,'') ~* '^[GDCZTKYSL][0-9]+' then 'HIGH_SPEED_RAIL' else 'PLANE' end),
  return_depart_city=coalesce(nullif(return_depart_city,''),regexp_replace(regexp_replace(coalesce(return_from,''),'国际机场.*$|机场.*$','','g'),'火车站$|高铁站$|站$','','g')),
  return_depart_station=case when coalesce(return_depart_transport_type,case when coalesce(return_no,'') ilike '%本地参会%' then 'LOCAL_ATTEND' when coalesce(return_no,'') ~* '^[GDCZTKYSL][0-9]+' then 'HIGH_SPEED_RAIL' else 'PLANE' end)='LOCAL_ATTEND' then null else coalesce(nullif(return_depart_station,''),nullif(return_from,'')) end,
  return_arrive_date=coalesce(return_arrive_date,return_date),
  return_arrive_transport_type=coalesce(return_arrive_transport_type,case when coalesce(return_no,'') ilike '%本地参会%' then 'LOCAL_ATTEND' when coalesce(return_no,'') ~* '^[GDCZTKYSL][0-9]+' then 'HIGH_SPEED_RAIL' else 'PLANE' end),
  return_arrive_city=coalesce(nullif(return_arrive_city,''),regexp_replace(regexp_replace(coalesce(return_to,''),'国际机场.*$|机场.*$','','g'),'火车站$|高铁站$|站$','','g')),
  return_arrive_station=case when coalesce(return_arrive_transport_type,case when coalesce(return_no,'') ilike '%本地参会%' then 'LOCAL_ATTEND' when coalesce(return_no,'') ~* '^[GDCZTKYSL][0-9]+' then 'HIGH_SPEED_RAIL' else 'PLANE' end)='LOCAL_ATTEND' then null else coalesce(nullif(return_arrive_station,''),nullif(return_to,'')) end;
