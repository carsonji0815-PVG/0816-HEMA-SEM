create or replace function public.replace_station_dictionary(p_items jsonb)
returns integer language plpgsql security definer set search_path=public as $$
declare v_count integer;
begin
  if not public.is_system_admin() then raise exception '仅超级管理员可维护场站字典'; end if;
  if jsonb_typeof(p_items) is distinct from 'array' then raise exception '场站字典格式错误'; end if;
  create temporary table tmp_station_dict(city_name text,transport_type text,station_name text,station_short_name text) on commit drop;
  insert into tmp_station_dict
  select btrim(city),btrim(type),btrim(name),nullif(btrim(short_name),'') from jsonb_to_recordset(p_items) as x(city text,type text,name text,short_name text);
  if exists(select 1 from tmp_station_dict where city_name='' or station_name='' or transport_type not in ('PLANE','HIGH_SPEED_RAIL')) then raise exception '场站字典包含无效数据'; end if;
  delete from public.station_dict;
  insert into public.station_dict(city_name,transport_type,station_name,station_short_name)
  select distinct city_name,transport_type,station_name,station_short_name from tmp_station_dict;
  get diagnostics v_count=row_count; return v_count;
end; $$;
revoke all on function public.replace_station_dictionary(jsonb) from public;
grant execute on function public.replace_station_dictionary(jsonb) to authenticated;

create or replace function public.guard_return_journey_columns()
returns trigger language plpgsql security definer set search_path=public as $$
begin
  if exists(select 1 from public.column_locks where meeting_id=old.meeting_id and field_group='return' and locked)
     and row(new.return_depart_date,new.return_depart_city,new.return_depart_transport_type,new.return_depart_station,new.return_arrive_date,new.return_arrive_city,new.return_arrive_transport_type,new.return_arrive_station)
       is distinct from row(old.return_depart_date,old.return_depart_city,old.return_depart_transport_type,old.return_depart_station,old.return_arrive_date,old.return_arrive_city,old.return_arrive_transport_type,old.return_arrive_station)
     and not public.is_system_admin() then raise exception '返程整列已锁定'; end if;
  if new.return_depart_transport_type='LOCAL_ATTEND' then new.return_depart_station:=null; end if;
  if new.return_arrive_transport_type='LOCAL_ATTEND' then new.return_arrive_station:=null; end if;
  return new;
end; $$;
drop trigger if exists attendees_guard_return_journey on public.attendees;
create trigger attendees_guard_return_journey before update on public.attendees for each row execute function public.guard_return_journey_columns();

